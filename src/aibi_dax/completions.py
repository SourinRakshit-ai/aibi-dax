"""Shell completion scripts, generated from the CLI's own parser.

`dxa --completions bash|zsh|fish` prints a script built by walking the
argparse structures returned by `cli._build_parser()` — subcommand names,
option strings and the rule inventory — so a new flag or rule is completable
the moment it exists and no flag list in this module can rot.
"""

from __future__ import annotations

import argparse

from .antipattern import ALL_RULES

SHELLS: tuple[str, ...] = ("bash", "zsh", "fish")


def _actions(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    """Every action a parser declared, in registration order."""
    return list(getattr(parser, "_actions", ()))


def option_strings(parser: argparse.ArgumentParser) -> list[str]:
    """Every option string the parser accepts (`--json`, `-h`, …)."""
    strings: list[str] = []
    for action in _actions(parser):
        strings.extend(action.option_strings)
    return strings


def subcommands(parser: argparse.ArgumentParser) -> dict[str, argparse.ArgumentParser]:
    """Map each registered subcommand name to its sub-parser.

    Read from the subparsers action's own choices, so the result tracks
    `_build_parser()` exactly — adding a subcommand makes it completable.
    """
    found: dict[str, argparse.ArgumentParser] = {}
    for action in _actions(parser):
        choices = getattr(action, "choices", None)
        if not isinstance(choices, dict):
            continue
        for name, target in choices.items():
            if isinstance(name, str) and isinstance(target, argparse.ArgumentParser):
                found[name] = target
    return found


def rule_names() -> list[str]:
    """Rule names, from the same inventory as `dxa lint --list-rules`."""
    return [rule.__name__ for rule in ALL_RULES]


def _takes_rule_option(parser: argparse.ArgumentParser) -> bool:
    """True for subcommands carrying a `--rule` filter (lint, lint-model)."""
    return any("--rule" in action.option_strings for action in _actions(parser))


def _has_rule_positional(parser: argparse.ArgumentParser) -> bool:
    """True for subcommands whose positional argument *is* a rule (explain)."""
    return any(
        action.dest == "rule" and not action.option_strings
        for action in _actions(parser)
    )


def _split_option(option: str) -> str:
    """`--min-weight` → `-l min-weight`; `-h` → `-s h` (fish syntax)."""
    if option.startswith("--"):
        return f"-l {option[2:]}"
    return f"-s {option[1:]}"


def _bash(parser: argparse.ArgumentParser) -> str:
    subs = subcommands(parser)
    top = " ".join(option_strings(parser))
    shells = " ".join(SHELLS)
    rules = " ".join(rule_names())
    out = [
        "# bash completion for dxa — generated by `dxa --completions bash`",
        (
            "# install: dxa --completions bash > "
            "~/.local/share/bash-completion/completions/dxa"
        ),
        "_dxa_complete() {",
        "    local cur prev i cmd",
        "    COMPREPLY=()",
        '    cur="${COMP_WORDS[COMP_CWORD]}"',
        '    prev="${COMP_WORDS[COMP_CWORD-1]}"',
        f'    local rules="{rules}"',
        "    cmd=\"\"",
        "    for ((i = 1; i < COMP_CWORD; i++)); do",
        '        case "${COMP_WORDS[i]}" in',
        "            -*) ;;",
        '            *) cmd="${COMP_WORDS[i]}"; break ;;',
        "        esac",
        "    done",
        '    if [[ -z "${cmd}" ]]; then',
        '        if [[ "${prev}" == "--completions" ]]; then',
        f'            COMPREPLY=( $(compgen -W "{shells}" -- "${{cur}}") )',
        '        elif [[ "${cur}" == -* ]]; then',
        f'            COMPREPLY=( $(compgen -W "{top}" -- "${{cur}}") )',
        "        else",
        f'            COMPREPLY=( $(compgen -W "{" ".join(subs)}" -- "${{cur}}") )',
        "        fi",
        "        return 0",
        "    fi",
        '    case "${cmd}" in',
    ]
    for name, sub in subs.items():
        opts = " ".join(option_strings(sub))
        out.append(f"        {name})")
        if _takes_rule_option(sub):
            out += [
                '            if [[ "${prev}" == "--rule" ]]; then',
                '                COMPREPLY=( $(compgen -W "${rules}" -- "${cur}") )',
                '            elif [[ "${cur}" == -* ]]; then',
                f'                COMPREPLY=( $(compgen -W "{opts}" -- "${{cur}}") )',
                "            fi",
                "            ;;",
            ]
        elif _has_rule_positional(sub):
            out += [
                '            if [[ "${cur}" == -* ]]; then',
                f'                COMPREPLY=( $(compgen -W "{opts}" -- "${{cur}}") )',
                "            else",
                '                COMPREPLY=( $(compgen -W "${rules}" -- "${cur}") )',
                "            fi",
                "            ;;",
            ]
        else:
            out += [
                '            if [[ "${cur}" == -* ]]; then',
                f'                COMPREPLY=( $(compgen -W "{opts}" -- "${{cur}}") )',
                "            fi",
                "            ;;",
            ]
    out += [
        "    esac",
        "    return 0",
        "}",
        "complete -F _dxa_complete dxa",
        "",
    ]
    return "\n".join(out)


def _zsh(parser: argparse.ArgumentParser) -> str:
    subs = subcommands(parser)
    top = " ".join(option_strings(parser))
    shells = " ".join(SHELLS)
    rules = " ".join(rule_names())
    out = [
        "#compdef dxa",
        "# zsh completion for dxa — generated by `dxa --completions zsh`",
        "# install: dxa --completions zsh > ~/.zfunc/_dxa  (fpath + compinit)",
        "#      or: source <(dxa --completions zsh)",
        "_dxa() {",
        "    local cur prev i cmd",
        '    cur="${words[CURRENT]}"',
        '    prev="${words[CURRENT-1]}"',
        f'    local rules="{rules}"',
        "    cmd=\"\"",
        "    for (( i = 2; i < CURRENT; i++ )); do",
        '        case "${words[i]}" in',
        "            -*) ;;",
        '            *) cmd="${words[i]}"; break ;;',
        "        esac",
        "    done",
        '    if [[ -z "${cmd}" ]]; then',
        '        if [[ "${prev}" == "--completions" ]]; then',
        f"            compadd -- {shells}",
        '        elif [[ "${cur}" == -* ]]; then',
        f"            compadd -- {top}",
        "        else",
        f"            compadd -- {' '.join(subs)}",
        "        fi",
        "        return 0",
        "    fi",
        '    case "${cmd}" in',
    ]
    for name, sub in subs.items():
        opts = " ".join(option_strings(sub))
        out.append(f"        {name})")
        if _takes_rule_option(sub):
            out += [
                '            if [[ "${prev}" == "--rule" ]]; then',
                '                compadd -- ${=rules}',
                '            elif [[ "${cur}" == -* ]]; then',
                f"                compadd -- {opts}",
                "            fi",
                "            ;;",
            ]
        elif _has_rule_positional(sub):
            out += [
                '            if [[ "${cur}" == -* ]]; then',
                f"                compadd -- {opts}",
                "            else",
                '                compadd -- ${=rules}',
                "            fi",
                "            ;;",
            ]
        else:
            out += [
                '            if [[ "${cur}" == -* ]]; then',
                f"                compadd -- {opts}",
                "            fi",
                "            ;;",
            ]
    out += [
        "    esac",
        "}",
        "compdef _dxa dxa",
        "",
    ]
    return "\n".join(out)


def _fish(parser: argparse.ArgumentParser) -> str:
    subs = subcommands(parser)
    shells = " ".join(SHELLS)
    rules = " ".join(rule_names())
    sub_list = " ".join(subs)
    out = [
        "# fish completion for dxa — generated by `dxa --completions fish`",
        "# install: dxa --completions fish > ~/.config/fish/completions/dxa.fish",
        "",
        "function __fish_dxa_needs_command",
        "    for i in (commandline -opc)",
        f"        if contains -- $i {sub_list}",
        "            return 1",
        "        end",
        "    end",
        "    return 0",
        "end",
        "",
    ]
    for action in _actions(parser):
        if not action.option_strings:
            continue
        flags = " ".join(_split_option(opt) for opt in action.option_strings)
        line = f"complete -c dxa -n '__fish_dxa_needs_command' {flags}"
        if action.nargs != 0:
            line += " -r"
        if action.dest == "completions":
            line += f" -a '{shells}'"
        out.append(line)
    for name in subs:
        out.append(
            f"complete -c dxa -n '__fish_dxa_needs_command' -a {name} -f"
        )
    out.append("")
    for name, sub in subs.items():
        cond = f"__fish_seen_subcommand_from {name}"
        for action in _actions(sub):
            if not action.option_strings:
                if action.dest == "rule":
                    out.append(
                        f"complete -c dxa -n '{cond}' -a '{rules}' -f"
                    )
                continue
            flags = " ".join(_split_option(opt) for opt in action.option_strings)
            line = f"complete -c dxa -n '{cond}' {flags}"
            if action.nargs != 0:
                line += " -r"
            if _takes_rule_option(sub) and "--rule" in action.option_strings:
                line += f" -a '{rules}' -f"
            if action.dest == "completions":
                line += f" -a '{shells}'"
            out.append(line)
    out.append("")
    return "\n".join(out)


def script(shell: str, parser: argparse.ArgumentParser) -> str:
    """The completion script for `shell`, generated from `parser`.

    Raises `ValueError` for a shell outside `SHELLS` — callers surface
    that as an exit-2 usage error naming the supported three.
    """
    if shell == "bash":
        return _bash(parser)
    if shell == "zsh":
        return _zsh(parser)
    if shell == "fish":
        return _fish(parser)
    raise ValueError(
        f"unsupported shell {shell!r} — choose one of: {', '.join(SHELLS)}"
    )
